/**
 * 核心用例: 编造动机。
 * 骨架的已知边界是"拦不住 L1 编一个说得通的动机"。
 * 这里试: 一个句子里没有任何线索, 却写了具体动作 —— 检查器能抓到吗?
 */
test("边界用例: 编造的动机能通过全部格式检查 —— 这是检查器的能力边界", () => {
  // 用户只说"你觉得呢", 原话里没有任何动作线索。
  // 但编出带动词的动机很容易 —— 动词白名单挡不住编造。
  const fabricated = `
## L1
- [动作] 想确认我的判断是否可靠
- [动作] 想知道我是否认真思考过
## L2
- [父:0][主观][当下][判断] 在问结论
- [父:1][主观][当下][判断] 在问过程
## L3
- [产出] 一个明确结论
`;
  const r = check(fabricated);
  // 断言: 它能通过 —— 这是能力边界, 必须被记录, 不能被假装解决
  assert.ok(r.ok, "格式检查无法发现'动机是编的': " + r.errors.join(";"));
});

test("[父:N] 越界能被发现 (曾漏, 已修)", () => {
  const r = check(`
## L1
- [动作] 想快速定位原因
- [动作] 想确认改动影响
## L2
- [父:9][主观][当下][判断] x
## L3
- [产出] 一个结论
`);
  assert.ok(!r.ok, "应发现越界");
  assert.ok(r.errors.some((e) => /越界/.test(e)), r.errors.join(";"));
});
